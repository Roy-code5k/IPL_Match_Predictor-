"""Phase 5, step 1: calibration review and confidence labels (pre-test data only).

Re-runs the Phase 4 comparison, checks that the frozen selection in
`src.models.confidence` still matches the selection rule, and reports calibration
and the confidence bands on the walk-forward 2015-2022 predictions.

Run from the project root:
    python -m src.models.calibration
"""

from __future__ import annotations

from pathlib import Path

from src.data.inspect_raw import md_table, tidy_markdown
from src.features import live as lf
from src.models import confidence as cf
from src.models import evaluation as ev
from src.models import live as lm
from src.models import prematch as pm

ROOT = Path(__file__).resolve().parents[2]
REPORT_PATH = ROOT / "reports" / "calibration_review.md"


def walk_forward_predictions():
    """Selected models' walk-forward predictions, after checking the frozen selection."""
    pre = pm.evaluate_candidates(pm.load_features())
    if pm.select(pre) != cf.SELECTED_PREMATCH:
        raise RuntimeError("Pre-match selection no longer matches SELECTED_PREMATCH")
    states = lm.load_states()
    live = {}
    for innings in (1, 2):
        results = lm.evaluate_innings(states, innings)
        if lm.select(results) != cf.SELECTED_LIVE[innings]:
            raise RuntimeError(f"Live innings {innings} selection no longer matches SELECTED_LIVE")
        live[innings] = results[cf.SELECTED_LIVE[innings]]
    return pre[cf.SELECTED_PREMATCH], live


def section(title: str, y, prob, target_label: str) -> str:
    return f"""
## {title}

Calibration ({target_label}):

{md_table(["Predicted range", "n", "Mean predicted", "Observed"], ev.calibration_table(y, prob, bins=10))}

Confidence bands (favourite = the side with the higher probability):

{md_table(cf.BAND_HEADERS, cf.band_table(y, prob))}
"""


def build_report(pre: dict, live: dict) -> str:
    wf = pre["walk_forward"]
    parts = [section(f"Pre-match: {pre['name']}", wf[pm.TARGET], wf["prob"], "Team A wins")]
    for innings, title in ((1, "Live, first innings"), (2, "Live, chase")):
        w = live[innings]["walk_forward"]
        parts.append(section(f"{title}: {live[innings]['name']}", w[lf.TARGET], w["prob"],
                             "batting-first side wins"))
    brk = live[2]["walk_forward"]
    brk = brk[brk["overs_done"] == 0]
    parts.append(section("Live, innings break only", brk[lf.TARGET], brk["prob"], "batting-first side wins"))

    bands = "\n".join(f"- **{name}:** favourite probability from {lowest:.0%}" for lowest, name in cf.BANDS)
    return tidy_markdown(f"""
# Calibration review and confidence labels (Phase 5)

Generated by `python -m src.models.calibration`. Uses only the walk-forward 2015–2022 predictions of the selected models (each season predicted by a model trained on earlier seasons). The 2023–2024 test seasons are not used.

## Decisions (fixed before the test evaluation)

- Selected models (from Phase 4): pre-match **{pre['name']}**; live **{live[1]['name']}** (first innings) and **{live[2]['name']}** (chase).
- Confidence labels use the favourite's probability:

{bands}

- "{cf.CLOSE}" is the low-confidence flag from PROJECT.md (a gap below 10 points between the two teams). The app must show it in text, not by colour alone.
- No recalibration. The pre-match model is close to calibrated. The live models are a few points overconfident between about 60% and 75% and well calibrated at the extremes. That S-shaped error would not be fixed by Platt or temperature scaling, and the band table below shows the real favourite win rate for each label.

{''.join(parts)}
""")


def main() -> int:
    pre, live = walk_forward_predictions()
    REPORT_PATH.write_text(build_report(pre, live), encoding="utf-8", newline="\n")
    print(f"Selection confirmed. Wrote {REPORT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
